import {readFile, writeFile} from 'node:fs/promises';
import ts from 'typescript';

// Read string literals via the TS AST, without executing browser/domain code.
const source = ts.createSourceFile(
  'categories.ts',
  await readFile(new URL('../src/data/categories.ts', import.meta.url), 'utf8'),
  ts.ScriptTarget.Latest,
  true,
);
let categories;
function visit(node) {
  if (
    ts.isVariableDeclaration(node) &&
    node.name.getText(source) === 'initialCategories'
  ) {
    if (!node.initializer || !ts.isArrayLiteralExpression(node.initializer)) {
      throw new Error('initialCategories must be a literal array.');
    }
    categories = node.initializer.elements.map(element => {
      if (!ts.isObjectLiteralExpression(element))
        throw new Error('Invalid category literal.');
      return Object.fromEntries(
        element.properties.map(property => {
          if (
            !ts.isPropertyAssignment(property) ||
            !ts.isStringLiteral(property.initializer)
          ) {
            throw new Error('Category properties must be string literals.');
          }
          return [
            property.name.getText(source).replace(/^['"]|['"]$/g, ''),
            property.initializer.text,
          ];
        }),
      );
    });
  }
  ts.forEachChild(node, visit);
}
visit(source);
const questions = JSON.parse(
  await readFile(
    new URL('../src/data/questions.json', import.meta.url),
    'utf8',
  ),
);
if (categories?.length !== 10 || questions.length !== 100)
  throw new Error('Expected 10 categories and 100 originals.');
const output = `-- Generated by scripts/generate-database-catalog.mjs. Never edit original texts here.
-- Once deployed, change catalog rules with a new migration, not by rewriting history.
create function private.original_categories()
returns table(id text, name text, color text, source text)
language sql immutable set search_path = '' as $function$
  select x.id, x.name, x.color, x.source
  from pg_catalog.jsonb_to_recordset($catalog$${JSON.stringify(categories)}$catalog$::jsonb)
    as x(id text, name text, color text, source text);
$function$;

create function private.original_questions()
returns table(id text, number integer, text text, category_id text, created_at timestamptz)
language sql stable set search_path = '' as $function$
  select x.id, x.number, x.text, x."categoryId", x."createdAt"
  from pg_catalog.jsonb_to_recordset($catalog$${JSON.stringify(questions)}$catalog$::jsonb)
    as x(id text, number integer, text text, "categoryId" text, "createdAt" timestamptz);
$function$;

revoke all on function private.original_categories(), private.original_questions()
  from public, anon, authenticated, service_role;
`;
const destination = new URL(
  '../supabase/migrations/20261105000200_original_catalog.sql',
  import.meta.url,
);
if (process.argv.includes('--write')) {
  await writeFile(destination, output, 'utf8');
} else if ((await readFile(destination, 'utf8')) !== output) {
  throw new Error(
    'SQL catalog differs from original data. Review before regenerating.',
  );
}
console.log(
  'Database catalog verified: 100 original questions and 10 categories.',
);
